using System.Text.Json.Serialization;

namespace Defra.WasteOrganisations.Api.Dtos;

// Every member has order -1, so it is written before the members a response type adds: the JSON
// of each response keeps the member order it had before these moved here

/// <summary>
/// The members that every v2 organisation response carries. A response type derives from this
/// and adds the members that differ between the create and the read (spec 0006, Decisions,
/// "Shared members"). Null members are omitted rather than written as null.
/// </summary>
public abstract record OrganisationResponseBase
{
    /// <summary>The id, a UUIDv7 generated by the API.</summary>
    [JsonPropertyName("id")]
    [JsonPropertyOrder(-1)]
    public required Guid Id { get; init; }

    /// <summary>The registered name; absent when none was sent.</summary>
    [JsonPropertyName("name")]
    [JsonPropertyOrder(-1)]
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public string? Name { get; init; }

    /// <summary>The name the organisation trades under; absent when none was sent.</summary>
    [JsonPropertyName("tradingName")]
    [JsonPropertyOrder(-1)]
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public string? TradingName { get; init; }

    /// <summary>The Companies House number; absent for a type not registered at Companies House.</summary>
    [JsonPropertyName("companiesHouseNumber")]
    [JsonPropertyOrder(-1)]
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public string? CompaniesHouseNumber { get; init; }

    /// <summary>The nation whose regulator the organisation deals with.</summary>
    [JsonPropertyName("regulatorNation")]
    [JsonPropertyOrder(-1)]
    public required RegulatorNation RegulatorNation { get; init; }
}
